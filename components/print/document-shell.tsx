import { getCompany } from "@/lib/frappe/companies";
import { PrintPageControls } from "@/components/common/print-page-controls";

/**
 * Shared A4 document shell for printable vouchers (invoices, payment
 * receipts, journal vouchers, …). Renders the company letterhead
 * (legal name + VAT/TIN + phone from the Company record), the document
 * title and number, optional status stamps, the body, and a footer.
 * Lives outside the workspace shell, so paper carries only the document.
 */
export async function DocumentShell({
  company,
  title,
  docNo,
  stamps = [],
  children,
}: {
  company: string;
  title: string;
  docNo: string;
  /** e.g. [{ text: "Draft — not yet issued" }, { text: "Cancelled", tone: "danger" }] */
  stamps?: Array<{ text: string; tone?: "danger" | "muted" }>;
  children: React.ReactNode;
}) {
  const info = await getCompany(company).catch(() => null);

  return (
    <div className="min-h-screen bg-muted/30 py-8 print:bg-white print:py-0">
      <PrintPageControls />

      <div className="mx-auto max-w-[210mm] bg-white p-10 text-[13px] leading-relaxed text-neutral-900 shadow-xl print:max-w-none print:p-0 print:shadow-none">
        <div className="flex items-start justify-between border-b-2 border-neutral-900 pb-4">
          <div>
            <div className="text-2xl font-bold tracking-tight">{company}</div>
            {info?.taxId && <div className="mt-1">VAT / TIN: {info.taxId}</div>}
            {info?.phoneNo && <div>Tel: {info.phoneNo}</div>}
          </div>
          <div className="text-right">
            <div className="text-xl font-bold tracking-wide">{title}</div>
            <div className="mt-1 font-mono">{docNo}</div>
            {stamps.map((s) => (
              <div
                key={s.text}
                className={
                  s.tone === "danger"
                    ? "mt-1 inline-block border border-red-600 px-2 py-0.5 text-xs font-bold uppercase tracking-wide text-red-600"
                    : "mt-1 inline-block border border-neutral-400 px-2 py-0.5 text-xs font-bold uppercase tracking-wide text-neutral-500"
                }
              >
                {s.text}
              </div>
            ))}
          </div>
        </div>

        {children}

        <div className="mt-10 border-t border-neutral-200 pt-3 text-center text-[11px] text-neutral-400">
          Generated by Colossal Suite · {new Date().toISOString().slice(0, 10)}
        </div>
      </div>
    </div>
  );
}

export function DocMetaRow({ label, value }: { label: string; value: React.ReactNode }) {
  return (
    <tr>
      <td className="pr-4 text-xs font-bold uppercase tracking-wide text-neutral-500">{label}</td>
      <td className="tabular-nums">{value}</td>
    </tr>
  );
}

export function DocTotalRow({ label, value, strong }: { label: string; value: string; strong?: boolean }) {
  return (
    <tr className={strong ? "font-bold" : ""}>
      <td className="py-1 text-neutral-600">{label}</td>
      <td className="py-1 text-right tabular-nums">{value}</td>
    </tr>
  );
}

export function DocSignatures({ labels }: { labels: string[] }) {
  return (
    <div
      className="mt-12 grid gap-10"
      style={{ gridTemplateColumns: `repeat(${labels.length}, minmax(0, 1fr))` }}
    >
      {labels.map((l) => (
        <div key={l}>
          <div className="h-10 border-b border-neutral-900" />
          <div className="mt-1 text-[10px] uppercase tracking-wide text-neutral-500">{l}</div>
        </div>
      ))}
    </div>
  );
}

export function docMoney(n: number): string {
  return n.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}
